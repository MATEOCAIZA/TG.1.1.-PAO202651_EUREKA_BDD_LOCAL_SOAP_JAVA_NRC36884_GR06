    private void cargarMovimientos(List<Movimiento> movimientos) {
    String[] columnas = {"N°", "Fecha", "Tipo", "Importe"};
    DefaultTableModel modelo = new DefaultTableModel(columnas, 0) {
        @Override
        public boolean isCellEditable(int row, int column) {
            return false;
        }
    };

    try {
        if (movimientos != null) {
            for (Movimiento mov : movimientos) {
                Object[] fila = {
                    mov.getNromov(),
                    mov.getFecha() != null ? mov.getFecha().toString() : "",
                    mov.getTipo(),
                    mov.getImporte()
                };
                modelo.addRow(fila);
            }
        }
        tableMovimientos.setModel(modelo);
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "❌ Error al cargar datos.", "Error", JOptionPane.ERROR_MESSAGE);
        e.printStackTrace();
    }
}

